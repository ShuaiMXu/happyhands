import {readFile,stat} from 'node:fs/promises';
import {resolve,relative,isAbsolute} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=fileURLToPath(new URL('../',import.meta.url));
const read=async path=>(await readFile(resolve(root,path),'utf8')).replaceAll('\r\n','\n');
const sourceRoot='.agents/skills/design-md/';
const source=JSON.parse(await read(sourceRoot+'source.json'));
const expected=['LICENSE.md','SKILL.md','references/design-md-template.md','references/skill-frontend-design.md'];
if(source.repository!=='https://github.com/nolly-studio/agent-skills'||source.revision!=='2008e7f671eb9f55989b73f9e33cbe06e74c428a'||source.version!=='1.0.0'||source.license!=='MIT'||JSON.stringify(source.files.map(file=>file.path).sort())!==JSON.stringify(expected))throw Error('Unexpected design-md source identity or inventory.');
for(const file of source.files){
  const content=await read(sourceRoot+file.path);
  if(createHash('sha256').update(content).digest('hex')!==file.sha256)throw Error('design-md source changed: '+file.path);
}

const template=await read(sourceRoot+'references/skill-frontend-design.md');
const start=template.indexOf('```md\n'),end=template.lastIndexOf('\n```');
if(start<0||end<=start)throw Error('Portable frontend-design template is unavailable.');
const portable=await read('.agents/skills/frontend-design/SKILL.md');
if(!portable.includes('<!-- generated by design-md v1.0.0 -->')||portable.replace('\n<!-- generated by design-md v1.0.0 -->\n','')!==template.slice(start+6,end)+'\n')throw Error('Portable frontend-design diverged from its pinned template.');
if(await read('.agents/skills/frontend-design/LICENSE.md')!==await read(sourceRoot+'LICENSE.md'))throw Error('Portable skill license is missing or changed.');

const design=await read('DESIGN.md'),agents=await read('AGENTS.md');
if(!design.startsWith('<!-- generated by design-md v1.0.0 -->\n')||!agents.includes('[Design Language](DESIGN.md)'))throw Error('Missing design contract stamp or agent entry link.');
for(const [name,content] of [['DESIGN.md',design],['AGENTS.md',agents]]){
  for(const match of content.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)){
    if(/^(?:https?:|#)/.test(match[1]))continue;
    const path=resolve(root,match[1].split('#')[0]),delta=relative(root,path);
    if(delta==='..'||delta.startsWith('../')||delta.startsWith('..\\')||isAbsolute(delta)||!(await stat(path)).isFile())throw Error('Invalid design documentation link: '+name+' → '+match[1]);
  }
}
const styles=await read('apps/designer/workbench-system.css');
const tokens=[...new Set([...design.matchAll(/`(--(?:ff|wb)-[\w-]+)`/g)].map(match=>match[1]))];
for(const token of tokens)if(!new RegExp(token+'\\s*:').test(styles))throw Error('Undeclared workbench design token: '+token);
console.log(`Design contract verified: ${source.files.length} pinned source files, portable skill, local links and ${tokens.length} declared tokens. This is not visual or human acceptance.`);
